// Regenerate when built-in geometry changes; hashes identify the exact recipes rendered by Three.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { PROP_SHAPE } from "../src/renderer/engine/palette/props";

const hash = (value) =>
  `sha256:${createHash("sha256").update(JSON.stringify(value)).digest("hex")}`;
const hashes = Object.fromEntries(
  Object.entries(PROP_SHAPE).map(([kind, recipe]) => [kind, hash(recipe)]),
);
writeFileSync(
  "src/shared/builtin-asset-hashes.ts",
  `// Generated by scripts/generate-asset-hashes.mjs from the actual renderer recipes.\nexport const BUILTIN_ASSET_HASHES = ${JSON.stringify(hashes, null, 2)} as const;\nexport const BUILTIN_PACK_HASH = ${JSON.stringify(hash(hashes))} as const;\n`,
);
